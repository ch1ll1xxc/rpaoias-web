; Микроопыт: почему ADD и ADC нельзя заменять двумя ADD.
; Это учебный пример, а не одна из двух обязательных программ.
.org 0
    MOV R0, 0xFFFF     ; В младшем слове уже 65535.
    MOV R1, 0          ; Старшее слово равно нулю.
    ADD R0, 1          ; R0=0000, CF=1: 65536 не помещается в 16 бит.
    ADC R1, 0          ; R1=0001 за счет входящего CF. Теперь R1:R0 = 65536.
    MOV [RESULT], R0   ; MOV не портит флаги.
    MOV [RESULT+2], R1
    MOV [RESULT+4], R2 ; R2 после reset равен 0.
    HALT
.org 0x0500
RESULT:
    .word 0, 0, 0
