; Вариант 2, задание 1: сумма знаковых элементов массива.
; Первый элемент ARRAY – количество последующих элементов, а не слагаемое.
; ОЗУ байтовая: одно 16-битное значение занимает ДВА адреса.
;
; R2:R1:R0 – 48-битный накопитель, от старшего слова к младшему.
; R3 – адрес текущего элемента; R5 – оставшееся количество.
; R6 – элемент; R7 – его знаковое расширение; R15 – статус (0=успех).

.entry start
.org 0
start:
    MOV R0, 0          ; Обнуляем младшие 16 бит накопителя.
    MOV R1, 0          ; Средние 16 бит – отдельный регистр, не Python int.
    MOV R2, 0          ; Старшие 16 бит; все три части вместе представляют сумму.
    MOV R15, 0         ; Это соглашение программы, не аппаратный флаг CPU.
    MOV R3, ARRAY      ; Без скобок имя метки означает ее АДРЕС.
    MOV R5, [R3]       ; Со скобками читаем слово ОЗУ по этому адресу: длину.
    ADD R3, 2          ; Пропускаем заголовок: он занимает два байта.
    CMP R5, 15         ; Для демонстрации принимаем длины 0..15.
    JC length_ok       ; CF=1 после CMP означает unsigned R5 < 15.
    JZ length_ok       ; Равенство 15 также допустимо.
    MOV R15, 1         ; Заголовок поврежден: не выходим за выделенный массив.
    HALT               ; Отладчик покажет ненулевой статус.

length_ok:
    CMP R5, 0          ; Нулевую длину обрабатываем до первой итерации.
    JZ done            ; Иначе SUB 0,1 превратил бы счетчик в 65535.
loop:
    MOV R6, [R3]       ; Косвенно-регистровая адресация: читаем текущий элемент.
    MOV R7, R6         ; Сохраняем копию для получения знакового расширения.
    SAR R7, 15         ; Для отрицательного числа R7=FFFF, иначе R7=0000.
    ADD R0, R6         ; Сумма младших частей формирует перенос CF.
    ADC R1, R7         ; Средние части + перенос из младшего слова.
    ADC R2, R7         ; Старшие части + НОВЫЙ перенос из среднего слова.
    ADD R3, 2          ; Только после цепочки ADC можно менять флаги счетчиками.
    SUB R5, 1          ; Уменьшаем число оставшихся элементов и обновляем ZF.
    JNZ loop           ; Возвращаемся, пока ZF=0, то есть счетчик не нулевой.

done:
    MOV [RESULT], R0    ; Сохраняем младшую часть результата в память.
    MOV [RESULT+2], R1  ; Следующее слово начинается через два байта.
    MOV [RESULT+4], R2  ; Старшая часть завершает 48-битное число.
    HALT               ; PC уже укажет за HALT; IR останется равен коду HALT.

.org 0x0400
ARRAY:
    .word 10           ; Длина массива, не один из десяти обрабатываемых элементов.
    .word 32767, 32767, -12, 8, -3, 100, -200, 50, -25, 7

.org 0x0500
RESULT:
    .word 0, 0, 0      ; Резервируем 6 байт: low, middle, high.
