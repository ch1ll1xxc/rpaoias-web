; Вариант 2, задание 2: S = сумма A[i]*B[i], по 10 знаковых элементов.
; В методичке эта формула названа "сверткой". Реализуем именно формулу (4.1).
;
; Произведение 16x16 требует 32 бит. Но сумма 10 таких произведений
; может достичь 10 * (-32768)^2 = 10737418240: это уже больше 32 бит.
; Поэтому используем R2:R1:R0 (48 бит), а НЕ одну 32-битную пару.
;
; R3, R4 – указатели A/B; R5 – счетчик; R7:R6 – произведение.
; R8 – знаковое расширение произведения; R9 – длина B; R15 – статус.

.entry start
.org 0
start:
    MOV R0, 0          ; Младшая треть длинного накопителя.
    MOV R1, 0          ; Средняя треть.
    MOV R2, 0          ; Старшая треть.
    MOV R15, 0         ; Статус самой программы: 0 означает успех.
    MOV R3, ARRAY_A    ; Адрес заголовка A.
    MOV R4, ARRAY_B    ; Адрес заголовка B.
    MOV R5, [R3]       ; Читаем длину A из ОЗУ, не зашиваем ее в цикл.
    MOV R9, [R4]       ; Второй массив тоже содержит собственный заголовок.
    CMP R5, R9         ; Скалярное произведение требует совпадения длин.
    JNZ invalid        ; Не используем молча минимум из двух длин.
    CMP R5, 10         ; Выделено место под 10 элементов каждого массива.
    JC length_ok       ; Длины 0..9 тоже допустимы для граничных тестов.
    JZ length_ok       ; Основной вариант задания: ровно 10.
invalid:
    MOV R15, 1         ; Разные или слишком большие длины – ошибка входных данных.
    HALT               ; Это ошибка программы, а не ошибка декодера процессора.

length_ok:
    ADD R3, 2          ; Перейти от заголовка A к A[0].
    ADD R4, 2          ; Перейти от заголовка B к B[0].
    CMP R5, 0          ; Пустые массивы дают нулевую сумму.
    JZ done            ; Не читаем ни одного элемента для длины 0.
loop:
    MOV R6, [R3]       ; Загрузить A[i] в регистр: только MOV обращается к данным ОЗУ.
    MOV R7, [R4]       ; Загрузить B[i]. Сам MUL не обращается к памяти.
    MUL R6, R7         ; Наша ISA: signed(R6)*signed(R7) -> R7:R6.
    MOV R8, R7         ; Знак 32-битного произведения находится в старшем слове.
    SAR R8, 15         ; Готовим третье слово: 0000 для плюса, FFFF для минуса.
    ADD R0, R6         ; Сложить младшие слова и получить CF.
    ADC R1, R7         ; Сложить средние слова с переносом из предыдущего ADD.
    ADC R2, R8         ; Сложить старшие слова с переносом из предыдущего ADC.
    ADD R3, 2          ; Шаг указателя равен размеру элемента, а не инструкции.
    ADD R4, 2          ; Следующий элемент B.
    SUB R5, 1          ; Последняя арифметическая команда перед JNZ задает ZF.
    JNZ loop           ; Управление потоком через PC, а не через цикл Python.

done:
    MOV [RESULT], R0    ; Три обычные пересылки записывают длинный результат.
    MOV [RESULT+2], R1
    MOV [RESULT+4], R2
    HALT

.org 0x0400
ARRAY_A:
    .word 10
    .word -32768, 32767, -30000, 30000, -25000, 25000, -20000, 20000, -15000, 15000
.org 0x0440
ARRAY_B:
    .word 10
    .word -32768, 32767, 30000, 30000, 25000, 25000, -20000, 20000, 15000, 15000
.org 0x0500
RESULT:
    .word 0, 0, 0      ; Порядок в памяти: младшее слово, среднее, старшее.
